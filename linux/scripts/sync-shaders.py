#!/usr/bin/env python3
"""Translate the shared HLSL pixel calculations to SkSL; no separate Linux effects model.

Run with --check in CI. Vertex placement is handled by the Skia draw-list encoder.
"""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "windows/src/AgentSpeed/Orb/Gpu/Shaders"
DEST = ROOT / "linux/src/AgentSpeed.Linux/Rendering/Shaders"


def remove_block(text, prefix):
    start = text.index(prefix)
    brace = text.index("{", start)
    level = 1
    end = brace + 1
    while level:
        level += (text[end] == "{") - (text[end] == "}")
        end += 1
    if text[end:end + 1] == ";":
        end += 1
    return text[:start] + text[end:]


def translate(text):
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"\[unroll\]", "", text)
    text = text.replace("static const", "const").replace("discard;", "return half4(0);")
    for before, after in (("saturate", "sat"), ("lerp", "mix"), ("atan2", "orb_atan2"), ("frac", "fract"),
                          ("degrees", "orb_degrees"), ("radians", "orb_radians"), ("smoothstep", "orb_smoothstep"),
                          ("pow", "orb_pow"), ("step", "orb_step"), ("round", "orb_round")):
        text = re.sub(r"\b" + before + r"\b", after, text)
    text = text.replace("pass_mode.x", "mode")
    # Skia 2's runtime language has no boolean function parameters.
    text = text.replace("bool dark = led_look.x > 0.5", "float dark = led_look.x")
    for flag in ("back", "dark", "additive"):
        text = text.replace("bool " + flag, "float " + flag)
        text = re.sub(r"\b" + flag + r"\s*\?", flag + " > 0.5 ?", text)
        text = text.replace("if (" + flag + ")", "if (" + flag + " > 0.5)")
    text = re.sub(r", (lq_\w+\.[xyzw]) > 0\.5\)", r", \1)", text)
    text = re.sub(r"\btrue\b", "1.0", text)
    text = re.sub(r"\bfalse\b", "0.0", text)
    text = text.replace("palette.SampleLevel(linear_clamp, float2(u, 0.5), 0)", "palette.eval(float2(u * 256.0, 0.5))")
    text = re.sub(r"\n\s*\n\s*\n", "\n\n", text)
    return text


def convert(name):
    common = (SOURCE / "OrbCommon.hlsl").read_text()
    common = common[common.index("float orb_clip_coverage"):]
    header = """// Generated by linux/scripts/sync-shaders.py from the existing HLSL calculations.
uniform float4 viewport;
uniform float4 transform;
uniform float4 globals;
uniform float mode;
uniform shader palette;
const float orb_tau = 6.28318530718;
float sat(float x) { return clamp(x, 0.0, 1.0); }
float2 sat(float2 x) { return clamp(x, 0.0, 1.0); }
float3 sat(float3 x) { return clamp(x, 0.0, 1.0); }
float4 sat(float4 x) { return clamp(x, 0.0, 1.0); }
float orb_atan2(float y, float x) {
    float ax = abs(x), ay = abs(y);
    float r = min(ax, ay) / max(max(ax, ay), 0.0000001);
    float q = r * r;
    float a = r * (1.0 + q * (-0.3302995 + q * (0.180141 + q * (-0.085133 + q * 0.0208351))));
    if (ay > ax) a = 1.57079632679 - a;
    if (x < 0.0) a = 3.14159265359 - a;
    return y < 0.0 ? -a : a;
}
float orb_degrees(float x) { return x * 57.2957795131; }
float orb_radians(float x) { return x * 0.01745329252; }
float orb_smoothstep(float a, float b, float x) { float t = clamp((x - a) / (b - a), 0.0, 1.0); return t * t * (3.0 - 2.0 * t); }
float orb_pow(float x, float y) { return x == 0.0 ? (y == 0.0 ? 1.0 : 0.0) : exp(log(x) * y); }
float3 orb_pow(float3 x, float y) { return float3(orb_pow(x.x, y), orb_pow(x.y, y), orb_pow(x.z, y)); }
float orb_step(float a, float x) { return x < a ? 0.0 : 1.0; }
float3 orb_step(float3 a, float3 x) { return float3(orb_step(a.x, x.x), orb_step(a.y, x.y), orb_step(a.z, x.z)); }
float4 orb_step(float4 a, float4 x) { return float4(orb_step(a.x, x.x), orb_step(a.y, x.y), orb_step(a.z, x.z), orb_step(a.w, x.w)); }
float orb_round(float x) { return floor(x + 0.5); }
"""
    text = (SOURCE / f"Orb{name}.hlsl").read_text()
    if name == "Shapes":
        text = text[text.index("float2 orb_rotate"):]
        text = remove_block(text, "ShapeOut VsShape")
        text = text.replace("float4 PsShape(ShapeOut input) : SV_Target", "half4 main(float2 canvas)")
        text = text.replace("input.local", "(canvas - shape_a.xy)").replace("input.canvas", "canvas")
        for field in ("extra2", "extra", "color2", "color", "a", "b"):
            text = text.replace("input." + field, "shape_" + field)
            header += f"uniform float4 shape_{field};\n"
    else:
        buffer = re.search(r"cbuffer[^\{]+\{(.+?)\};", text, re.S)
        header += re.sub(r"\bfloat4\b", "uniform float4", buffer.group(1))
        text = text[buffer.end():]
        out = "LiquidOut" if name == "Liquid" else "LedOut"
        text = remove_block(text, "struct " + out)
        text = remove_block(text, out + " Vs" + name)
        text = text.replace(f"float4 Ps{name}({out} input) : SV_Target", "half4 main(float2 canvas)")
        text = text.replace("input.canvas", "canvas")
        # The original corona interpolates slow noise between ring vertices. Evaluate it directly here.
        text = text.replace("input.body", "(0.5 + 0.5 * led_noise(float3(p / max(r, 0.0001) * 2.2, led_halo.x * 0.35)))")
    result = translate(header + common + text).strip()
    return "// LED simplex noise: Ashima Arts / Stefan Gustavson (MIT); see source HLSL.\n" + "\n".join(line.rstrip() for line in result.splitlines()) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name in ("Shapes", "Liquid", "Led"):
        target = DEST / f"{name}.sksl"
        expected = convert(name)
        if args.check:
            if not target.exists() or target.read_text() != expected:
                raise SystemExit(f"Stale shader: {target}; run linux/scripts/sync-shaders.py")
        else:
            DEST.mkdir(parents=True, exist_ok=True)
            target.write_text(expected)


if __name__ == "__main__":
    main()
